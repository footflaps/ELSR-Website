#!/bin/bash

# -------------------------------------------------------------------------------------------------------------- #
# -------------------------------------------------------------------------------------------------------------- #
# Backup ELSR locally on GCP
# -------------------------------------------------------------------------------------------------------------- #
# -------------------------------------------------------------------------------------------------------------- #

# -------------------------------------------------------------------------------------------------------------- #
# Colours (ANSI escape codes)
# -------------------------------------------------------------------------------------------------------------- #
RED=$(printf '\033[0;31m')
GREEN=$(printf '\033[0;32m')
YELLOW=$(printf '\033[1;33m')
BLUE=$(printf '\033[0;34m')
MAGENTA=$(printf '\033[0;35m')
CYAN=$(printf '\033[0;36m')
WHITE=$(printf '\033[1;37m')
CLEAR=$(printf '\033[0m')


# -------------------------------------------------------------------------------------------------------------- #
# Header
# -------------------------------------------------------------------------------------------------------------- #

echo -e ""
echo -e "# -------------------------------------------------------------------------------------------------------------- #"
echo -e "${MAGENTA}     Running & pulling backup from ELSR GCP server ${CLEAR}"
echo -e "# -------------------------------------------------------------------------------------------------------------- #"
echo -e ""


# -------------------------------------------------------------------------------------------------------------- #
# Constants
# -------------------------------------------------------------------------------------------------------------- #

# Backup Timestamp (eg 2025-12-30)
DATE=$(date +%F)

# Backup location on GCP
REMOTE_BACKUP_DIR="/home/deploy/backups/$DATE"

# Backup script location on GCP
REMOTE_SCRIPT_DIR="/home/deploy/elsr"

# Local backup dir
LOCAL_BACKUP_DIR="$HOME/ELSR_Admin/backups/gcp/${DATE}"


# -------------------------------------------------------------------------------------------------------------- #
# Run backup on GCP
# -------------------------------------------------------------------------------------------------------------- #
echo -e "-- Running backup on ${CYAN}GCP${CLEAR}..."
ssh elsr2 <<EOF
  set -e
  cd "${REMOTE_SCRIPT_DIR}"
  sudo ./elsr_local_backup.sh
EOF


# -------------------------------------------------------------------------------------------------------------- #
# Pull backup off GCP
# -------------------------------------------------------------------------------------------------------------- #
echo -e "-- Pulling backup ${CYAN}${DATE}${CLEAR} from ${CYAN}GCP${CLEAR}..."

mkdir -p "${LOCAL_BACKUP_DIR}"

scp -r "elsr2:${REMOTE_BACKUP_DIR}/*" "${LOCAL_BACKUP_DIR}/"


# -------------------------------------------------------------------------------------------------------------- #
# Done
# -------------------------------------------------------------------------------------------------------------- #
echo -e ""
echo -e "Backup Complete: ${CYAN}${LOCAL_BACKUP_DIR}/${CLEAR}"
echo -e ""

exit




